"""Negative-control parents built by builders/pce.py (PB-01: partially protonated VPEG-type with Na+;
PB-02: three block-copolymer chains with Ca2+), each in CVFF-INTERFACE and PCFF-INTERFACE.

  python scripts/build_pce_parents.py   -> data/reference/pce_builder/PB-0x_{pcff,cvff}.data + .json
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from builders.pce import ArchitectureSpec, build  # noqa: E402

OUT = os.path.join(ROOT, "data", "reference", "pce_builder")

if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for pid, ex in (("PB-01", "vpeg_partial"), ("PB-02", "block_multichain")):
        for ff in ("pcff", "cvff"):
            d = json.load(open(os.path.join(ROOT, "examples", "pce", f"{ex}.json")))
            d.update(force_field=ff, name=f"{pid}_{ff}")
            p = os.path.join(OUT, f"{pid}_{ff}.data")
            if os.path.exists(p):
                os.chmod(p, 0o644)
            rec = build(ArchitectureSpec.from_json(d), OUT)
            for ext in ("car", "mdf"):
                os.remove(os.path.join(OUT, f"{pid}_{ff}.{ext}"))
            os.chmod(p, 0o444)
            meta = {"id": f"{pid}_{ff}", "role": "BUILDER_OUTPUT_PARENT", "file": os.path.relpath(p, ROOT),
                    "sha256": rec["data_sha256"], "source": f"builders/pce.py examples/pce/{ex}.json (force_field {ff}, seed {d['seed']})",
                    "declared_config": f"configs/interface_{ff}_pce.yaml", "overrides": {},
                    "trust_status": "generated by builders/pce.py and validated (all tiers); used as a negative-control parent only"}
            json.dump(meta, open(os.path.join(OUT, f"{pid}_{ff}.json"), "w"), indent=2)
            print(pid, ff, rec["natoms"])
