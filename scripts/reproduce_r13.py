"""R13 reproduction (SPEC §7.13; FAILURE_MODES §9.3): ASE read -> write round trip of LAMMPS DATA FILEs.

The matsci.org thread (R13) reports type swaps, a lost Masses section, a reset box origin and
changed coordinates after a default ase.io.read / ase.io.write round trip. Its exact input file
is not used here; instead the group's own references are round-tripped, one argument changed at a
time, and each output is judged by the validator (with TC.2 against the original).

  python scripts/reproduce_r13.py      -> data/converted/ase/*.data, docs/R13_ASE_ROUNDTRIP.md

ASE is used here only as the *converter under test*, never inside the validator.
"""
from __future__ import annotations

import datetime as _dt
import json
import os
import sys
import traceback

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import ase  # noqa: E402
import ase.io  # noqa: E402

from validator import validate  # noqa: E402
from validator.registry import config_for, load_sidecar  # noqa: E402

OUT = os.path.join(ROOT, "data", "converted", "ase")
REFS = ["data/reference/REF-04.data", "data/reference/REF-01.data"]

# (variant, read kwargs, write kwargs) — each changes one argument relative to the previous.
VARIANTS = [
    ("defaults", {}, {}),
    ("read_full", {"atom_style": "full"}, {}),
    ("read_full_write_full", {"atom_style": "full"}, {"atom_style": "full"}),
    ("+units_real", {"atom_style": "full", "units": "real"}, {"atom_style": "full", "units": "real"}),
    ("+masses", {"atom_style": "full", "units": "real"}, {"atom_style": "full", "units": "real", "masses": True}),
    ("+specorder", {"atom_style": "full", "units": "real"},
     {"atom_style": "full", "units": "real", "masses": True, "specorder": "__file_order__"}),
]


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for ref in REFS:
        rpath = os.path.join(ROOT, ref)
        meta = load_sidecar(rpath)
        for name, rkw, wkw in VARIANTS:
            out = os.path.join(OUT, f"{meta['id']}__ase_{name}.data")
            note = ""
            try:
                atoms = ase.io.read(rpath, format="lammps-data", **rkw)
                wk = dict(wkw)
                if wk.get("specorder") == "__file_order__":
                    seen = []
                    for s in atoms.get_chemical_symbols():
                        if s not in seen:
                            seen.append(s)
                    wk["specorder"] = seen
                ase.io.write(out, atoms, format="lammps-data", **wk)
            except Exception as e:
                rows.append({"ref": meta["id"], "variant": name, "read": rkw, "write": wkw, "error":
                             f"{type(e).__name__}: {e}", "trace": traceback.format_exc(limit=2)})
                continue
            side = dict(meta, id=f"{meta['id']}__ase_{name}", role="CONVERTER_OUTPUT", parent_id=meta["id"],
                        parent_file=ref, converter=f"ase {ase.__version__}", read_kwargs=rkw, write_kwargs=wkw)
            with open(os.path.splitext(out)[0] + ".json", "w") as fh:
                json.dump(side, fh, indent=2, default=str)
            res = validate(out, config_for(out, side), reference=rpath)
            fails = [f"{c.property}" for c in res.checks if c.verdict == "FAIL"]
            first = next((c for c in res.checks if c.verdict == "FAIL"), None)
            tc = res.get("TC.2")
            rows.append({"ref": meta["id"], "variant": name, "read": rkw, "write": wkw, "verdict": res.verdict,
                         "failing": fails, "first": f"{first.property}: {first.message}" if first else "",
                         "tc2": tc.details.get("differences", []) if tc else [],
                         "natoms_symbols": sorted(set(atoms.get_chemical_symbols())), "note": note})
    write_report(rows)
    for r in rows:
        print(r["ref"], r["variant"], r.get("verdict", "ERROR"), r.get("failing", r.get("error")))


def write_report(rows):
    L = ["# R13 reproduction — ASE lammps-data round trip\n",
         f"Generated by `scripts/reproduce_r13.py` on {_dt.date.today().isoformat()} with ASE {ase.__version__} "
         "(the converter under test; the validator does not use ASE). Inputs: candidate references REF-04 "
         "(40 atoms) and REF-01 (1478 atoms). Each output is validated under the parent's declared configuration, "
         "with TC.2 against the parent. The R13 thread's own input file was **not** used, so this reproduces the "
         "*class* of behaviour, not that exact report.\n",
         "| Ref | Variant | read kwargs | write kwargs | Verdict | Failing properties | First failure | TC.2 differences |",
         "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if "error" in r:
            L.append(f"| {r['ref']} | {r['variant']} | `{r['read']}` | `{r['write']}` | ERROR | — | {r['error'][:140]} | — |")
            continue
        L.append(f"| {r['ref']} | {r['variant']} | `{r['read']}` | `{r['write']}` | {r['verdict']} | "
                 f"{', '.join(dict.fromkeys(r['failing'])) or '—'} | {r['first'][:160]} | "
                 f"{'; '.join(r['tc2'][:3])[:220] or '—'} |")
    with open(os.path.join(ROOT, "docs", "R13_ASE_ROUNDTRIP.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
