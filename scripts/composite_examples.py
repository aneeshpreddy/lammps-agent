"""Build every composite in examples/composite/ (PCE on a mineral surface) in both force fields and
validate each file.

  python scripts/composite_examples.py   -> data/generated/composite/<name>_<ff>.data (+ .build.json)
                                           docs/COMPOSITE.md

A force field without parameters for the slab (CVFF-INTERFACE has only C3S and C3A) is a refusal, reported
as a result.
"""
from __future__ import annotations

import datetime as _dt
import glob
import json
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from builders.composite import build  # noqa: E402
from validator import load_config, validate  # noqa: E402

OUT = os.path.join(ROOT, "data", "generated", "composite")
CONFIG = {"pcff": "configs/interface_pcff_composite.yaml", "cvff": "configs/interface_cvff_composite.yaml"}


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for f in sorted(glob.glob(os.path.join(ROOT, "examples", "composite", "*.json"))):
        d = json.load(open(f))
        for ff in ("pcff", "cvff"):
            dd = dict(d, force_field=ff, name=f"{d['name']}_{ff}")
            row = {"example": os.path.basename(f).replace(".json", ""), "ff": ff, "surface": d["surface"]["model"]}
            t0 = time.time()
            try:
                rec = build(dd, OUT)
            except Exception as e:                       # refusal (missing parameters, does not fit) is a result
                row.update({"built": False, "error": str(e).splitlines()[0][:150]})
                rows.append(row)
                print(row["example"], ff, "refused")
                continue
            row["build_s"] = round(time.time() - t0, 1)
            res = validate(os.path.join(OUT, dd["name"] + ".data"), load_config(declared=CONFIG[ff]))
            row.update({"built": True, "natoms": rec["natoms"], "slab_atoms": rec["slab_atoms"], "pce_atoms": rec["pce_atoms"],
                        "supercell": rec["supercell"], "normal": rec["surface_normal"], "height": rec["height_A"],
                        "closest": rec["closest_pce_slab_distance_A"], "box": rec["box"], "orientation": rec["orientation"],
                        "verdict": res.verdict, "tier_reached": res.tier_reached,
                        "not_pass": [f"{c.property}:{c.verdict}" for c in res.checks if c.verdict not in ("PASS", "NOT_APPLICABLE")]})
            rows.append(row)
            print(row["example"], ff, row["verdict"], row["natoms"])
    with open(os.path.join(OUT, "summary.json"), "w") as fh:
        json.dump(rows, fh, indent=2)
    write_report(rows)


def write_report(rows):
    L = ["# Composite builder — PCE on a cement-mineral surface\n",
         f"Generated by `scripts/composite_examples.py` on {_dt.date.today().isoformat()}. Supervisor 2026-10-26: "
         "\"yes a combined builder\" (SPEC §7.17). `builders/composite.py` builds the PCE (`builders/pce.py`: relaxed, "
         "tight box) and the slab (`builders/minerals.py`), finds the surface normal (the axis with the largest empty "
         "gap), lays the PCE flat (shortest principal axis along the normal) or keeps it as built, lifts its lowest atom "
         "to the requested height above the topmost slab atom, and merges the two DATA FILEs with every PCE type, atom, "
         "molecule and topology ID offset; coefficient rows are copied unchanged. A lateral supercell of `auto` is the "
         "smallest one that leaves a 4 Å gap between the PCE and its periodic image. Each file is judged by the "
         "validator (Tiers 0–3, `configs/interface_{pcff,cvff}_composite.yaml`). Files: `data/generated/composite/`.\n",
         "| Example | FF | Surface | Supercell | Normal | Atoms (slab + PCE) | Height / closest contact (Å) | Box (Å) | Verdict | Build (s) | Notes |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if not r.get("built"):
            L.append(f"| {r['example']} | {r['ff']} | {r['surface']} | — | — | — | — | — | **refused** | — | {r['error']} |")
            continue
        L.append(f"| {r['example']} | {r['ff']} | {r['surface']} | {'×'.join(map(str, r['supercell']))} | {r['normal']} | "
                 f"{r['natoms']} ({r['slab_atoms']} + {r['pce_atoms']}) | {r['height']} / {r['closest']} | "
                 f"{' × '.join(f'{v:.1f}' for v in r['box'])} | {r['verdict']} | {r['build_s']} | "
                 f"{r['orientation']}{'; not PASS: ' + ', '.join(r['not_pass']) if r['not_pass'] else ''} |")
    built = [r for r in rows if r.get("built")]
    ok = sum(1 for r in built if r["verdict"] == "PASS")
    L += ["", f"**{ok} / {len(built)} built composites PASS every tier**; {len(rows) - len(built)} refused (no parameters "
          "for the slab in that force field).", "",
          "**Limits.** No water or bulk ions are added; the PCE geometry is the builder's relaxed vacuum conformation "
          "(no adsorption equilibration); the TC layer checks chemistry and the lateral cell, not the height or "
          "orientation (METRICS.md v1.1)."]
    with open(os.path.join(ROOT, "docs", "COMPOSITE.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
