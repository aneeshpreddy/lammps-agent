"""Sanity checks of the evaluation harness (plan Day 21) -> docs/HARNESS.md.

  python scripts/harness_checks.py [--repeats 3]

Runs on the dev split only (the test split stays closed until 16 Nov):
  oracle                 builds the hidden spec                     expect success = 1.00
  baseline (mock)        the baseline's own code path with a "perfect model" that answers with the
                         hidden spec in the baseline's output schema                expect success = 1.00
  corrupt-file           oracle file + one corruption operator      expect success <= 0.05, validity <= 0.05
  corrupt-spec           a slightly different system, built cleanly expect success <= 0.05, validity >= 0.95
  agent (mock)           perfect / fix / stubborn / wrongvalid scripted models (agents/mock.py)
  agent-checked (mock)   variant E with the wrongvalid model         expect success = 1.00 in 2 attempts
"""
from __future__ import annotations

import argparse
import datetime as _dt
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from eval.harness import evaluate, load_tasks  # noqa: E402
from eval.systems import make_system  # noqa: E402

CHECKS = [
    ("oracle", None, lambda a: a["system_success_rate"] == 1.0, "success = 1.00"),
    ("baseline", "perfect", lambda a: a["system_success_rate"] == 1.0, "success = 1.00"),
    ("corrupt-file", None, lambda a: a["system_success_rate"] <= 0.05 and a["validity_rate"] <= 0.05,
     "success ≤ 0.05 and validity ≤ 0.05"),
    ("corrupt-spec", None, lambda a: a["system_success_rate"] <= 0.05 and a["validity_rate"] >= 0.95,
     "success ≤ 0.05 and validity ≥ 0.95"),
    # agent loop with scripted mock models (agents/mock.py): checks the loop's control flow, not a model
    ("agent", "perfect", lambda a: a["system_success_rate"] == 1.0 and a["mean_attempts"] == 1.0,
     "success = 1.00 in 1 attempt"),
    ("agent", "fix", lambda a: a["system_success_rate"] == 1.0 and a["recovery_rate"] == 1.0
     and a["mean_attempts"] == round(1 + 9 / 13, 3), "success = 1.00; the 9 PCE/composite tasks recover in attempt 2"),
    ("agent", "stubborn", lambda a: a["system_success_rate"] == round(4 / 13, 4)
     and a["escalations"] == round(9 / 13 * a["runs"]), "success = 4/13 (minerals); the 9 PCE/composite tasks escalate"),
    # variant E (agents/checks.py): a valid but wrong first build
    ("agent", "wrongvalid", lambda a: a["system_success_rate"] <= 0.05 and a["validity_rate"] >= 0.95
     and a["mean_attempts"] == 1.0, "success ≤ 0.05, validity ≥ 0.95, 1 attempt (C accepts the wrong build)"),
    ("agent-checked", "wrongvalid", lambda a: a["system_success_rate"] == 1.0 and a["mean_attempts"] == 2.0,
     "success = 1.00 in 2 attempts (the request check catches it)"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repeats", type=int, default=3)
    a = ap.parse_args()
    tasks = load_tasks("dev")
    stamp = _dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    rows = []
    for name, mock, ok, crit in CHECKS:
        system = make_system(name, mock=mock)
        out = os.path.join(ROOT, "runs", "eval", f"check_{system.meta['name']}_{stamp}")
        res = evaluate(system, tasks, a.repeats, out, log=lambda s: print(f"  {name}: {s}"))
        agg = res["aggregate"]
        rows.append((system.meta["name"], crit, agg, ok(agg), res["fixed_conditions"], out))
        print(f"{system.meta['name']}: success {agg['system_success_rate']}, validity {agg['validity_rate']} -> "
              f"{'OK' if ok(agg) else 'FAILED'}")
    write(rows, tasks, a.repeats)
    return 0 if all(r[3] for r in rows) else 1


def write(rows, tasks, repeats):
    fc = rows[0][4]
    L = ["# Evaluation harness — sanity checks (plan Day 21)\n",
         f"Generated by `scripts/harness_checks.py` on {_dt.date.today().isoformat()} · git {fc['git_commit'][:7]}"
         f"{' (dirty)' if fc['git_dirty'] else ''} · validator {fc['validator_version']} · split {fc['split_sha256'][:12]}… · "
         f"{fc['lammps']}. Dev split ({len(tasks)} tasks: {', '.join(t['id'] for t in tasks)}) × {repeats} repeats. "
         "The harness (`eval/harness.py`) scores a run as a success iff the validator passes every Tier 0–3 check "
         "and TC.2 matches the task's reference in its mode (METRICS.md v1.2). Full runs: `runs/eval/` (gitignored).\n",
         "| System | What it does | Expected | Success | Validity | Failure categories | Result |",
         "|---|---|---|---|---|---|---|"]
    what = {"oracle": "builds the hidden spec with the builders",
            "baseline-mock-perfect": "the baseline's code path (schema → builder spec → build) with a mock model that "
                                     "answers with the hidden spec",
            "corrupt-file": "oracle file + one corruption operator (scripts/mutate.py), rotating over 8 operators",
            "corrupt-spec": "builds a slightly different system (one more cell / EO unit / unit)",
            "agent-mock-perfect": "the agent loop with a mock model: example lookup, build of the hidden spec, stop",
            "agent-mock-fix": "the agent loop with a mock model whose first build has a defect the validator catches "
                              "(PCE without counter-ions) or the builder refuses (mistyped mineral model); fixed after feedback",
            "agent-mock-stubborn": "the agent loop with a mock model that repeats its defective build whatever the feedback",
            "agent-mock-wrongvalid": "the agent loop (C) with a mock model whose first build is valid but a slightly "
                                     "different system (as corrupt-spec); fixed only if told",
            "agent-checked-mock-wrongvalid": "variant E (C + build summary + request check) with the same mock; the mock "
                                             "answers the request check's extraction call from the hidden spec"}
    for name, crit, agg, ok, _, out in rows:
        cats = ", ".join(f"{k} {v}" for k, v in agg["failure_categories"].items()) or "—"
        L.append(f"| {name} | {what.get(name, '')} | {crit} | {agg['system_success_rate']:.3f} | {agg['validity_rate']:.3f} | "
                 f"{cats} | {'**OK**' if ok else '**FAILED**'} |")
    L += ["", "**Why each check matters.** The oracle shows that a correct file is always scored a success (no false "
          "failures from the harness, configurations or references). The mock baseline shows that the baseline's "
          "output schema can express every dev task and that its conversion to builder specs is faithful, so a "
          "baseline failure is the model's, not the glue's. The file corrupter shows that invalid files are not "
          "scored as successes; the spec corrupter shows that valid files of the wrong system are not either (TC.2 "
          "does its job). The three agent checks show that the loop validates every attempt, turns a caught defect "
          "into feedback that leads to a fix and a scored success, and stops a model that repeats its failure "
          "(escalation) — all with scripted models, so they check the loop, not a model. The last two show the known "
          "limitation of C (a valid but wrong build is accepted, and only TC.2 afterwards sees it) and that variant E's "
          "request check closes it when the request states the field (here the mock's extraction is perfect, so this "
          "checks the plumbing, not the extraction)."]
    with open(os.path.join(ROOT, "docs", "HARNESS.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    sys.exit(main())
