"""References for every INTERFACE cement-mineral model in every supported force field ("let it learn
about all", supervisor 2026-10-20).

  python scripts/build_mineral_references.py   -> data/reference/minerals/<model>_<ff>.data + .json
                                                 calibration/minerals_{pcff,cvff}.json
                                                 docs/MINERALS.md

Every model in UGRP/CEMENT_MINERALS is built with builders/minerals.py in PCFF-INTERFACE (class II)
and CVFF-INTERFACE (class I). A force field that lacks parameters for a model is recorded as
unsupported (the builder refuses rather than writing zeros). Each built file is then calibrated
against (per force field) and validated through Tier 3.
"""
from __future__ import annotations

import datetime as _dt
import glob
import json
import os
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from builders.minerals import KNOWN_DEFECTIVE, build_mineral, list_models  # noqa: E402
from validator import validate  # noqa: E402
from validator.registry import config_for  # noqa: E402

OUT = os.path.join(ROOT, "data", "reference", "minerals")
CONFIG = {"pcff": "configs/interface_pcff_minerals.yaml", "cvff": "configs/interface_cvff_minerals.yaml"}
CEMENT = os.path.join(os.path.dirname(ROOT), "CEMENT_MINERALS")


def family(model: str) -> str:
    return "surface" if "_surface" in model else model


def main():
    os.makedirs(OUT, exist_ok=True)
    models = [m for m, d in list_models().items() if os.path.samefile(d, CEMENT)]
    rows = []
    for model in sorted(models):
        for ff in ("pcff", "cvff"):
            row = {"model": model, "ff": ff}
            if model in KNOWN_DEFECTIVE:
                row.update({"built": False, "reason": "defective database entry: " + KNOWN_DEFECTIVE[model]})
                rows.append(row)
                continue
            name = f"{model}_{ff}"
            path = os.path.join(OUT, name + ".data")
            if os.path.exists(path):
                os.chmod(path, 0o644)
            try:
                rec = build_mineral(model, (1, 1, 1), ff, OUT, name)
            except RuntimeError as e:
                row.update({"built": False, "reason": str(e).split(":")[0] + ": " + str(e).split(":", 2)[-1][:120]})
                rows.append(row)
                continue
            os.chmod(path, 0o444)
            tilted = any(abs(float(x)) > 0 for x in open(path).read().split("xy xz yz")[0].split("\n")[-1].split()) \
                if "xy xz yz" in open(path).read() else False
            meta = {"id": name, "role": "REFERENCE_PUBLISHED_MODEL", "file": os.path.relpath(path, ROOT),
                    "sha256": rec["data_sha256"], "declared_config": CONFIG[ff],
                    "overrides": {"density_family": family(model), "box_kind": "triclinic" if tilted else "any"},
                    "trust_status": "PUBLISHED MODEL (INTERFACE FF 1.5) + documented pipeline; supervisor confirmation pending",
                    "build": {k: v for k, v in rec.items() if k != "data_file"}}
            with open(os.path.join(OUT, name + ".json"), "w") as fh:
                json.dump(meta, fh, indent=2)
            row.update({"built": True, "natoms": rec["natoms"], "file": os.path.relpath(path, ROOT),
                        "cross_terms_zeroed": rec["cross_terms_zeroed"]})
            rows.append(row)
            print(name, rec["natoms"])
    # calibrate per force field from the files just built
    subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "calibrate.py"), "minerals_pcff", "minerals_cvff"],
                   check=True)
    for r in rows:
        if not r.get("built"):
            continue
        t0 = time.time()
        path = os.path.join(ROOT, r["file"])
        res = validate(path, config_for(path))
        r.update({"verdict": res.verdict, "tier_reached": res.tier_reached, "validate_s": round(time.time() - t0, 1),
                  "not_pass": [f"{c.property}:{c.verdict}" for c in res.checks if c.verdict not in ("PASS", "NOT_APPLICABLE")],
                  "first_problem": next((c.message[:120] for c in res.checks if c.verdict == "FAIL"), "")})
        print(r["model"], r["ff"], r["verdict"], r["not_pass"])
    with open(os.path.join(OUT, "summary.json"), "w") as fh:
        json.dump(rows, fh, indent=2)
    report(rows)


def report(rows):
    L = ["# Cement minerals — references in both force fields\n",
         f"Generated by `scripts/build_mineral_references.py` on {_dt.date.today().isoformat()}. Every INTERFACE FF 1.5 "
         "model in `UGRP/CEMENT_MINERALS` built with `builders/minerals.py` (msi2lmp → tilt reduction + wrap → "
         "LAMMPS read/write) and validated through Tier 3 (`configs/interface_{pcff,cvff}_minerals.yaml`, Ewald). "
         "A force field that lacks parameters for a model is reported, never filled with zeros.\n",
         "| Model | PCFF-INTERFACE (class II) | CVFF-INTERFACE (class I) |", "|---|---|---|"]
    by = {}
    for r in rows:
        by.setdefault(r["model"], {})[r["ff"]] = r
    for model, d in sorted(by.items()):
        cells = []
        for ff in ("pcff", "cvff"):
            r = d.get(ff, {})
            if not r.get("built"):
                cells.append("not available — " + r.get("reason", "")[:90])
            else:
                extra = f"; {', '.join(r['not_pass'])}" if r.get("not_pass") else ""
                cells.append(f"**{r['verdict']}** ({r['natoms']} atoms, tier {r['tier_reached']}{extra})")
        L.append(f"| {model} | {cells[0]} | {cells[1]} |")
    built = [r for r in rows if r.get("built")]
    L += ["", f"**{sum(r['verdict'] == 'PASS' for r in built)} / {len(built)} built references PASS every tier.** "
          "Class II cross terms are not defined for the INTERFACE mineral types and are zero in every PCFF build "
          "(INTERFACE convention). Tier 2 bond windows and contact floors for minerals are calibrated from these same "
          "files (`calibration/minerals_*.json`), so for them Tier 2 is a consistency check; Tiers 0, 1 and 3 are independent."]
    with open(os.path.join(ROOT, "docs", "MINERALS.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
