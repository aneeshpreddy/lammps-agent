"""Checks of the tool layer without any LLM (plan Days 26-27) -> docs/TOOLS.md, section "Checks".

  python scripts/tool_checks.py

1. Every reference example (tools/examples.py) is fetched with get_reference_example, built with
   build_data_file and validated (Tiers 0-3, declared configuration of its family): it must PASS, since
   get_reference_example promises known-good examples.
2. get_model_info answers for every cement-mineral model in both force fields (ok, or a refusal that
   names the covering force field).
3. Every call is in the JSONL log with the plan's fields.
"""
from __future__ import annotations

import datetime as _dt
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from tools.examples import EXAMPLES  # noqa: E402
from tools.facts import FORCE_FIELDS, cement_models  # noqa: E402
from tools.toolbox import TOOLS_VERSION, ToolBox, definitions  # noqa: E402
from validator import __version__ as VALIDATOR_VERSION, load_config, validate  # noqa: E402

DOC = os.path.join(ROOT, "docs", "TOOLS.md")
LOG_FIELDS = {"ts", "call", "tool", "arguments", "ok", "result", "duration_s"}


def example_config(spec: dict):
    b, ff = spec["builder"], spec["force_field"]
    family = {"minerals": "minerals", "pce": "pce", "composite": "composite"}[b]
    overrides = {"density_family": spec["model"]} if b == "minerals" else {}
    return load_config(declared=f"configs/interface_{ff}_{family}.yaml", overrides={"declared": overrides})


def main():
    work = tempfile.mkdtemp(prefix="tool_checks_")
    tb = ToolBox(work)
    rows, ok_all = [], True
    for kind, ex in EXAMPLES.items():
        inp = tb.run("get_reference_example", {"kind": kind})["build_data_file_input"]
        t0 = time.time()
        r = tb.run("build_data_file", inp)
        if not r["ok"]:
            rows.append((kind, False, "build failed: " + r["error"], "", 0.0))
            ok_all = False
            continue
        res = validate(tb.last_build, example_config(ex["spec"]))
        not_pass = sorted(f"{c.property}:{c.verdict}" for c in res.checks if c.verdict not in ("PASS", "NOT_APPLICABLE"))
        good = bool(res.passed)
        ok_all &= good
        rows.append((kind, good, res.verdict + (f" ({', '.join(not_pass)})" if not_pass else ""),
                     f"{r['facts']['atoms']} atoms, {r['facts']['elements']}", round(time.time() - t0, 1)))
        print(f"{kind}: {res.verdict} {not_pass}")
    info = {"ok": 0, "refused": 0, "unexpected": []}
    for m in cement_models():
        for ff in FORCE_FIELDS:
            r = tb.run("get_model_info", {"model": m, "force_field": ff})
            if r["ok"]:
                info["ok"] += 1
            elif re.search(r"not available in|defective", r["error"]):
                info["refused"] += 1
            else:
                info["unexpected"].append(f"{m}/{ff}: {r['error']}")
    ok_all &= not info["unexpected"]
    lines = [json.loads(l) for l in open(tb.log_path)]
    log_ok = len(lines) == tb.n_calls and all(LOG_FIELDS <= set(l) for l in lines)
    ok_all &= log_ok
    write(rows, info, len(lines), log_ok)
    shutil.rmtree(work)
    print("tool checks:", "OK" if ok_all else "FAILED")
    return 0 if ok_all else 1


def write(rows, info, n_log, log_ok):
    git = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    dirty = bool(subprocess.run(["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True).stdout.strip())
    L = ["## Checks (generated)\n",
         f"Generated by `scripts/tool_checks.py` on {_dt.date.today().isoformat()} · git {git}{' (dirty)' if dirty else ''} · "
         f"{TOOLS_VERSION} · validator {VALIDATOR_VERSION}. No LLM involved.\n",
         "**Reference examples:** each is built with `build_data_file` and validated (Tiers 0–3, the declared "
         "configuration of its family; no TC, there is no task reference). All must PASS.\n",
         "| Example | Validator | Built | Build + validation (s) |", "|---|---|---|---|"]
    L += [f"| `{k}` | {'PASS' if good else '**' + v + '**'} | {facts} | {s} |" for k, good, v, facts, s in rows]
    L += ["", f"**get_model_info:** {len(cement_models())} cement-mineral models × {len(FORCE_FIELDS)} force fields: "
          f"{info['ok']} answered, {info['refused']} refused with the covering force field or the defect named, "
          f"{len(info['unexpected'])} unexpected errors.\n",
          f"**Log:** {n_log} calls, one JSON line each with {', '.join(sorted(LOG_FIELDS))}: "
          f"{'complete' if log_ok else '**incomplete**'}.\n"]
    text = open(DOC).read()
    head = text.split("## Checks (generated)")[0].rstrip() + "\n\n"
    open(DOC, "w").write(head + "\n".join(L))


if __name__ == "__main__":
    sys.exit(main())
