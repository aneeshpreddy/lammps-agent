"""Build every PCE architecture in examples/pce/ in both force fields and validate each file.

  python scripts/pce_examples.py   -> data/generated/pce/<name>_<ff>.data (+ .build.json, .car/.mdf)
                                     docs/PCE_BUILDER.md

For architectures that copy a group EMC model ("emc_reference"), the generated file's composition
and topology counts are compared with the EMC file — two independent builders, same molecule.
"""
from __future__ import annotations

import datetime as _dt
import glob
import json
import os
import sys
import time
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from builders.pce import ArchitectureSpec, build  # noqa: E402
from validator import load_config, validate  # noqa: E402
from validator.parser import parse_file  # noqa: E402

OUT = os.path.join(ROOT, "data", "generated", "pce")
CONFIG = {"pcff": "configs/interface_pcff_pce.yaml", "cvff": "configs/interface_cvff_pce.yaml"}
COUNTS = ("atoms", "bonds", "angles", "dihedrals", "impropers")


def composition(path):
    pf = parse_file(path)
    masses = {int(r.tokens[0]): float(r.tokens[1]) for r in pf.section("Masses").rows}
    sym = {1: "H", 12: "C", 16: "O", 23: "Na", 40: "Ca", 39: "K"}
    return dict(sorted(Counter(sym.get(round(masses[int(r.tokens[2])]), "?") for r in pf.section("Atoms").rows).items())), \
        {k: pf.header_int(k) for k in COUNTS}


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for f in sorted(glob.glob(os.path.join(ROOT, "examples", "pce", "*.json"))):
        d = json.load(open(f))
        if d.get("name") == "olig_test":
            continue
        for ff in ("pcff", "cvff"):
            dd = dict(d, force_field=ff, name=f"{d['name']}_{ff}")
            row = {"example": os.path.basename(f), "name": dd["name"], "ff": ff}
            t0 = time.time()
            try:
                rec = build(ArchitectureSpec.from_json(dd), OUT)
            except Exception as e:                       # refusal (missing parameters) is a result
                row.update({"built": False, "error": str(e).splitlines()[0][:160]})
                rows.append(row)
                continue
            row["build_s"] = round(time.time() - t0, 1)
            data = os.path.join(OUT, dd["name"] + ".data")
            res = validate(data, load_config(declared=CONFIG[ff]))
            comp, counts = composition(data)
            row.update({"built": True, "natoms": rec["natoms"], "counts": counts, "composition": comp,
                        "net_charge": rec["net_charge"], "chain_charges": rec["chain_charges"],
                        "counterions": rec["counterions"], "cross_terms_zeroed": rec.get("cross_terms_zeroed"),
                        "verdict": res.verdict, "tier_reached": res.tier_reached,
                        "failing": [c.property for c in res.checks if c.verdict == "FAIL"],
                        "not_pass": [f"{c.property}:{c.verdict}" for c in res.checks
                                     if c.verdict not in ("PASS", "NOT_APPLICABLE")],
                        "sequence": rec["sequences"][0] if rec["sequences"] else ""})
            ref = d.get("emc_reference")
            if ref:
                rcomp, rcounts = composition(os.path.join(ROOT, "data", "reference", f"{ref}.data"))
                same_counts = {k: counts[k] == rcounts[k] for k in COUNTS}
                if ff == "cvff":
                    same_counts.pop("impropers")          # class I defines impropers only at planar centres
                row["emc"] = {"reference": ref, "composition_equal": comp == rcomp, "counts_equal": all(same_counts.values()),
                              "reference_counts": rcounts}
            rows.append(row)
            print(row["name"], row.get("verdict"), row.get("natoms"), row.get("emc", ""))
    with open(os.path.join(OUT, "summary.json"), "w") as fh:
        json.dump(rows, fh, indent=2)
    write_report(rows)


def write_report(rows):
    L = ["# PCE builder — examples in both force fields\n",
         f"Generated by `scripts/pce_examples.py` on {_dt.date.today().isoformat()}. Each architecture in "
         "`examples/pce/` is built with `builders/pce.py` in **PCFF-INTERFACE (class II)** and **CVFF-INTERFACE "
         "(class I)**, then judged by the validator (Tiers 0–3, `configs/interface_{pcff,cvff}_pce.yaml`; Tier 2 "
         "tolerances from the group's EMC files, not from the builder). Files: `data/generated/pce/`.\n",
         "| Architecture | FF | Atoms | Bonds / angles / dihedrals / impropers | Composition | Chain charge → counter-ions | Verdict | Build (s) | Notes |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        if not r.get("built"):
            L.append(f"| {r['example']} | {r['ff']} | — | — | — | — | **refused** | — | {r['error']} |")
            continue
        c = r["counts"]
        comp = " ".join(f"{k}{v}" for k, v in r["composition"].items())
        notes = []
        if r.get("emc"):
            e = r["emc"]
            notes.append(f"EMC {e['reference']}: composition {'identical' if e['composition_equal'] else 'DIFFERENT'}, "
                         f"counts {'identical' if e['counts_equal'] else 'DIFFERENT'}")
        if r.get("cross_terms_zeroed"):
            notes.append("class II cross terms absent for INTERFACE PEO types (zero)")
        if r["not_pass"]:
            notes.append("not PASS: " + ", ".join(r["not_pass"]))
        L.append(f"| {r['example'].replace('.json', '')} | {r['ff']} | {r['natoms']} | {c['bonds']} / {c['angles']} / "
                 f"{c['dihedrals']} / {c['impropers']} | {comp} | {r['chain_charges']} → {r['counterions']} | "
                 f"{r['verdict']} | {r['build_s']} | {'; '.join(notes) or '—'} |")
    ok = sum(1 for r in rows if r.get("verdict") == "PASS")
    L += ["", f"**{ok} / {len(rows)} builds PASS every tier.**"]
    with open(os.path.join(ROOT, "docs", "PCE_BUILDER.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
